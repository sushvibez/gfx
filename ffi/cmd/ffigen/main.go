// ffigen generates typed, reflection-free stubs for native functions.
//
// It reads a Go package directory, finds every `lib.Bind(&name, "symbol")`
// whose variable is declared as a func type, and for each signature it can
// express as "up to six integer-sized arguments, at most one integer-sized
// result" emits a real Go function of the same name that calls through
// ffi.Call (an assembly trampoline: no reflection, no allocation). The
// var declaration and the Bind call are removed from the hand-written
// files; a generated bindGenerated(lib) resolves the addresses instead.
// Signatures it cannot express (floats, by-value structs, more than six
// arguments) are left alone and reported, so they keep going through
// purego.RegisterFunc.
//
//	ffigen -dir ../gpu -out zffi_gen.go [-dry]
package main

import (
	"bytes"
	"flag"
	"fmt"
	"go/ast"
	"go/format"
	"go/parser"
	"go/printer"
	"go/token"
	"os"
	"path/filepath"
	"regexp"
	"sort"
	"strings"
)

type fn struct {
	name, sym string
	file      string
	typ       *ast.FuncType
	params    []param
	ret       string // Go type of the result, "" for none
}

type param struct{ name, typ string }

func main() {
	dir := flag.String("dir", ".", "package directory to scan")
	out := flag.String("out", "zffi_gen.go", "generated file name (inside -dir)")
	dry := flag.Bool("dry", false, "report what would be generated, change nothing")
	tag := flag.String("tag", "!js", "build constraint for the generated file")
	flag.Parse()

	fset := token.NewFileSet()
	// Stubs generated earlier are recovered from the generated file itself
	// (their declarations and the symbols bindGenerated resolves), so a
	// rerun is a merge: the hand-written files no longer declare them.
	prior, err := priorStubs(fset, filepath.Join(*dir, *out))
	if err != nil {
		fatal(err)
	}
	pkgs, err := parser.ParseDir(fset, *dir, func(fi os.FileInfo) bool {
		return !strings.HasSuffix(fi.Name(), "_test.go") && fi.Name() != *out
	}, parser.ParseComments)
	if err != nil {
		fatal(err)
	}
	var pkg *ast.Package
	for _, p := range pkgs {
		pkg = p
	}
	if pkg == nil {
		fatal(fmt.Errorf("no package in %s", *dir))
	}

	// 1. func-typed package-level vars. A name declared in more than one
	// file is a per-platform variant (build-tagged signatures that differ,
	// like a struct-by-value request on SysV and by-pointer on Win64) and
	// stays on Bind: the generated file carries one constraint for all.
	vars := map[string]*fn{}
	declFiles := map[string]int{}
	for path, f := range pkg.Files {
		for _, d := range f.Decls {
			gd, ok := d.(*ast.GenDecl)
			if !ok || gd.Tok != token.VAR {
				continue
			}
			for _, s := range gd.Specs {
				vs := s.(*ast.ValueSpec)
				ft, ok := vs.Type.(*ast.FuncType)
				if !ok || len(vs.Values) != 0 {
					continue
				}
				for _, n := range vs.Names {
					vars[n.Name] = &fn{name: n.Name, file: path, typ: ft}
					declFiles[n.Name]++
				}
			}
		}
	}
	// 2. Bind calls.
	bindFile := map[string]string{}
	for path, f := range pkg.Files {
		ast.Inspect(f, func(n ast.Node) bool {
			c, ok := n.(*ast.CallExpr)
			if !ok {
				return true
			}
			sel, ok := c.Fun.(*ast.SelectorExpr)
			if !ok || sel.Sel.Name != "Bind" || len(c.Args) != 2 {
				return true
			}
			u, ok := c.Args[0].(*ast.UnaryExpr)
			if !ok || u.Op != token.AND {
				return true
			}
			id, ok := u.X.(*ast.Ident)
			if !ok {
				return true
			}
			lit, ok := c.Args[1].(*ast.BasicLit)
			if !ok {
				return true
			}
			if v := vars[id.Name]; v != nil {
				v.sym = strings.Trim(lit.Value, `"`)
				bindFile[id.Name] = path
			}
			return true
		})
	}

	var gen, skipped []*fn
	for _, v := range vars {
		if v.sym == "" {
			continue
		}
		if declFiles[v.name] > 1 {
			fmt.Fprintf(os.Stderr, "ffigen: keep %s on RegisterFunc: declared in %d files (platform variants)\n", v.name, declFiles[v.name])
			skipped = append(skipped, v)
			continue
		}
		if why := classify(fset, v); why != "" {
			fmt.Fprintf(os.Stderr, "ffigen: keep %s on RegisterFunc: %s\n", v.name, why)
			skipped = append(skipped, v)
			continue
		}
		gen = append(gen, v)
	}
	fresh := len(gen)
	for _, p := range prior {
		if vars[p.name] == nil {
			gen = append(gen, p)
		}
	}
	sort.Slice(gen, func(i, j int) bool { return gen[i].name < gen[j].name })
	fmt.Fprintf(os.Stderr, "ffigen: %d stubs (%d new, %d kept from %s), %d kept on RegisterFunc\n", len(gen), fresh, len(gen)-fresh, *out, len(skipped))
	if *dry {
		for _, g := range gen {
			fmt.Println(g.name, g.params, g.ret)
		}
		return
	}

	// 3. Emit.
	var b bytes.Buffer
	fmt.Fprintf(&b, "// Code generated by ffigen; DO NOT EDIT.\n\n//go:build %s\n\npackage %s\n\n", *tag, pkg.Name)
	needUnsafe := false
	for _, g := range gen {
		if g.ret == "unsafe.Pointer" || strings.HasPrefix(g.ret, "*") {
			needUnsafe = true
		}
		for _, p := range g.params {
			if !isInt(p.typ) {
				needUnsafe = true
			}
		}
	}
	b.WriteString("import (\n")
	if needUnsafe {
		b.WriteString("\t\"unsafe\"\n\n")
	}
	b.WriteString("\t\"github.com/sushvibez/gfx/ffi\"\n)\n\n")
	b.WriteString("// Symbol addresses, resolved by bindGenerated.\nvar (\n")
	for _, g := range gen {
		fmt.Fprintf(&b, "\taddr_%s uintptr\n", g.name)
	}
	b.WriteString(")\n\n")
	for _, g := range gen {
		var ps, args []string
		for i, p := range g.params {
			name := p.name
			if name == "" || name == "_" {
				name = fmt.Sprintf("a%d", i)
			}
			ps = append(ps, name+" "+p.typ)
			args = append(args, toUintptr(name, p.typ))
		}
		for len(args) < 6 {
			args = append(args, "0")
		}
		call := fmt.Sprintf("ffi.Call(addr_%s, %s)", g.name, strings.Join(args, ", "))
		fmt.Fprintf(&b, "func %s(%s)", g.name, strings.Join(ps, ", "))
		switch g.ret {
		case "":
			fmt.Fprintf(&b, " {\n\t%s\n}\n\n", call)
		case "uintptr":
			fmt.Fprintf(&b, " uintptr {\n\treturn %s\n}\n\n", call)
		case "bool":
			fmt.Fprintf(&b, " bool {\n\treturn %s != 0\n}\n\n", call)
		case "unsafe.Pointer":
			fmt.Fprintf(&b, " unsafe.Pointer {\n\tr := %s\n\treturn *(*unsafe.Pointer)(unsafe.Pointer(&r))\n}\n\n", call)
		default:
			if strings.HasPrefix(g.ret, "*") {
				fmt.Fprintf(&b, " %s {\n\tr := %s\n\treturn (%s)(*(*unsafe.Pointer)(unsafe.Pointer(&r)))\n}\n\n", g.ret, call, g.ret)
			} else {
				fmt.Fprintf(&b, " %s {\n\treturn %s(%s)\n}\n\n", g.ret, g.ret, call)
			}
		}
	}
	b.WriteString("// bindGenerated resolves every generated stub's symbol. Missing symbols\n// panic, like ffi.Bind: a binding error is a programming error.\nfunc bindGenerated(lib *ffi.Lib) {\n")
	for _, g := range gen {
		fmt.Fprintf(&b, "\taddr_%s = lib.MustSym(%q)\n", g.name, g.sym)
	}
	b.WriteString("}\n")
	src, err := format.Source(b.Bytes())
	if err != nil {
		os.WriteFile(filepath.Join(*dir, *out+".broken"), b.Bytes(), 0o644)
		fatal(fmt.Errorf("format: %w (see %s.broken)", err, *out))
	}
	if err := os.WriteFile(filepath.Join(*dir, *out), src, 0o644); err != nil {
		fatal(err)
	}

	// 4. Strip the var declarations and Bind calls from the hand-written files.
	names := map[string]bool{}
	for _, g := range gen {
		names[g.name] = true
	}
	touched := map[string]bool{}
	for _, g := range gen {
		if g.file == filepath.Join(*dir, *out) {
			continue // a stub kept from the previous run: nothing to strip
		}
		touched[g.file] = true
		if bf := bindFile[g.name]; bf != "" {
			touched[bf] = true
		}
	}
	varRe := regexp.MustCompile(`^\s*(\w+)\s+func\(`)
	bindRe := regexp.MustCompile(`^\s*lib\.Bind\(&(\w+),`)
	for path := range touched {
		data, err := os.ReadFile(path)
		if err != nil {
			fatal(err)
		}
		var keep []string
		for _, line := range strings.Split(string(data), "\n") {
			if m := varRe.FindStringSubmatch(line); m != nil && names[m[1]] {
				continue
			}
			if m := bindRe.FindStringSubmatch(line); m != nil && names[m[1]] {
				continue
			}
			keep = append(keep, line)
		}
		src := strings.Join(keep, "\n")
		// Empty `var (\n)` blocks left behind.
		src = regexp.MustCompile(`(?m)^var \(\n\)\n`).ReplaceAllString(src, "")
		formatted, err := format.Source([]byte(src))
		if err != nil {
			fatal(fmt.Errorf("%s after stripping: %w", path, err))
		}
		if err := os.WriteFile(path, formatted, 0o644); err != nil {
			fatal(err)
		}
	}
}

// classify fills params/ret, returning a reason when the signature cannot
// go through ffi.Call.
func classify(fset *token.FileSet, f *fn) string {
	n := 0
	for _, fld := range f.typ.Params.List {
		typ := exprString(fset, fld.Type)
		if !supported(typ) {
			return "parameter type " + typ
		}
		cnt := max(len(fld.Names), 1)
		for i := 0; i < cnt; i++ {
			name := ""
			if len(fld.Names) > 0 {
				name = fld.Names[i].Name
			}
			f.params = append(f.params, param{name, typ})
		}
		n += cnt
	}
	if n > 6 {
		return fmt.Sprintf("%d arguments", n)
	}
	if f.typ.Results != nil {
		if len(f.typ.Results.List) > 1 {
			return "multiple results"
		}
		r := exprString(fset, f.typ.Results.List[0].Type)
		if !supported(r) && r != "bool" {
			return "result type " + r
		}
		f.ret = r
	}
	return ""
}

func isInt(t string) bool {
	switch t {
	case "uintptr", "uint", "uint8", "uint16", "uint32", "uint64", "int", "int8", "int16", "int32", "int64":
		return true
	}
	return false
}

func supported(t string) bool {
	return isInt(t) || t == "unsafe.Pointer" || strings.HasPrefix(t, "*")
}

func toUintptr(name, typ string) string {
	switch {
	case typ == "uintptr":
		return name
	case isInt(typ):
		return "uintptr(" + name + ")"
	default:
		return "uintptr(unsafe.Pointer(" + name + "))"
	}
}

func exprString(fset *token.FileSet, e ast.Expr) string {
	var b bytes.Buffer
	printer.Fprint(&b, fset, e)
	return b.String()
}

func fatal(err error) {
	fmt.Fprintln(os.Stderr, "ffigen:", err)
	os.Exit(1)
}

// priorStubs reads the stubs an earlier run generated: every top-level
// func in the generated file whose address var bindGenerated resolves.
func priorStubs(fset *token.FileSet, path string) ([]*fn, error) {
	src, err := os.ReadFile(path)
	if os.IsNotExist(err) {
		return nil, nil
	}
	if err != nil {
		return nil, err
	}
	f, err := parser.ParseFile(fset, path, src, 0)
	if err != nil {
		return nil, fmt.Errorf("%s: %w", path, err)
	}
	syms := map[string]string{} // stub name -> symbol
	ast.Inspect(f, func(n ast.Node) bool {
		as, ok := n.(*ast.AssignStmt)
		if !ok || len(as.Lhs) != 1 || len(as.Rhs) != 1 {
			return true
		}
		id, ok := as.Lhs[0].(*ast.Ident)
		if !ok || !strings.HasPrefix(id.Name, "addr_") {
			return true
		}
		call, ok := as.Rhs[0].(*ast.CallExpr)
		if !ok || len(call.Args) != 1 {
			return true
		}
		if lit, ok := call.Args[0].(*ast.BasicLit); ok {
			syms[strings.TrimPrefix(id.Name, "addr_")] = strings.Trim(lit.Value, `"`)
		}
		return true
	})
	var out []*fn
	for _, d := range f.Decls {
		fd, ok := d.(*ast.FuncDecl)
		if !ok || fd.Recv != nil {
			continue
		}
		sym, ok := syms[fd.Name.Name]
		if !ok {
			continue
		}
		v := &fn{name: fd.Name.Name, sym: sym, file: path, typ: fd.Type}
		if why := classify(fset, v); why != "" {
			return nil, fmt.Errorf("%s: generated stub %s: %s", path, v.name, why)
		}
		out = append(out, v)
	}
	return out, nil
}
