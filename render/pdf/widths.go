// standardWidths picks the metric set a standard-14 base font uses, and
// the width to fall back on outside the tabulated range.
func standardWidths(base Name) (map[int]float32, float32) {
	s := string(base)
	if i := indexByte(s, '+'); i >= 0 && i+1 < len(s) {
		s = s[i+1:] // strip a subset tag ("ABCDEF+Helvetica")
	}
	bold := containsFold(s, "Bold") || containsFold(s, "Black") || containsFold(s, "Heavy")
	switch {
	case containsFold(s, "Courier") || containsFold(s, "Mono"):
		return nil, 600 // fixed pitch
	case containsFold(s, "Times") || containsFold(s, "Serif") || containsFold(s, "Roman") ||
		containsFold(s, "Georgia") || containsFold(s, "Book"):
		if bold {
			return widthsTimesBold, 500
		}
		return widthsTimes, 500
	}
	if bold {
		return widthsHelveticaBold, 556
	}
	return widthsHelvetica, 556
}

// containsFold is a case-insensitive substring test (font names vary).
func containsFold(s, sub string) bool {
	if len(sub) == 0 || len(s) < len(sub) {
		return len(sub) == 0
	}
	lower := func(c byte) byte {
		if c >= 'A' && c <= 'Z' {
			return c + 32
		}
		return c
	}
	for i := 0; i+len(sub) <= len(s); i++ {
		ok := true
		for j := 0; j < len(sub); j++ {
			if lower(s[i+j]) != lower(sub[j]) {
				ok = false
				break
			}
		}
		if ok {
			return true
		}
	}
	return false
}
